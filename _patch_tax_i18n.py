def esc(value: str) -> str:
    return value.replace("\\", "\\\\").replace("'", "\\'")

def main():
    en = (ROOT / "en.ts").read_text(encoding="utf-8")
    needed = []
    for line in en.splitlines():
        s = line.strip()
        if s.startswith("'nav.tax'") or s.startswith("'page.tax.") or s.startswith("'tax."):
            key = s.split("'", 2)[1]
            needed.append(key)
    if len(needed) < 70:
        raise SystemExit(f"expected tax keys in en.ts, found {len(needed)}")
    for locale, pairs in T.items():
        missing = [k for k in needed if k not in pairs]
        extra = [k for k in pairs if k not in needed]
        if missing or extra:
            raise SystemExit(f"{locale} missing {missing} extra {extra}")
        path = ROOT / f"{locale}.ts"
        text = path.read_text(encoding="utf-8")
        if "'nav.tax'" in text:
            raise SystemExit(f"{locale} already patched")
        block = "".join(f"  '{k}': '{esc(pairs[k])}',\n" for k in needed)
        needle = "};\n\nexport default"
        if needle not in text:
            raise SystemExit(f"needle missing in {locale}")
        path.write_text(text.replace(needle, block + needle, 1), encoding="utf-8")
        print(locale, len(needed))

if __name__ == "__main__":
    main()
